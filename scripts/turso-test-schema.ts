#!/usr/bin/env bun
// Keeps tls-sqld-test on production's schema. Run after a tls-dashboard-v2 migration:
// `TURSO_TEST_AUTH_TOKEN=... with-agent-env bun scripts/turso-test-schema.ts` syncs, `--check` reports and writes nothing.
// Production is read with one fixed SELECT through Hrana `/v2/pipeline` and nothing else; rows are never selected.
// tls-sqld-test is reached through testDbExec only, reads and writes alike. The full DDL lives in tls-sqld-test:
// this repo is public, so only the tables tests touch are committed, in server/lib/turso-test-schema.sql.

import { join } from "node:path"
import { type ExecFn, tursoExec } from "../server/lib/turso"
import { TEST_HOST, testDbUrl } from "../server/lib/turso-test-guard.test-util"

export const PROD_READ = "SELECT type,name,tbl_name,sql FROM sqlite_master"
const PROD_URL = "https://tls-sqld-1016439101738.northamerica-northeast1.run.app/v2/pipeline"
const SUBSET_FILE = join(import.meta.dir, "../server/lib/turso-test-schema.sql")
const SUBSET_TABLES = ["agent_activity", "notes", "task_stamps", "tasks"]
// Columns no test touches whose name alone says more than a public repo should. tls-test keeps them (extra columns pass).
const SUBSET_DROP_COLS = ["canvas_room_secret"]
const RANK = ["table", "view", "index", "trigger"]

export interface Obj { type: string; name: string; tbl: string; sql: string }

/** `turso db shell` output: fixed-width columns, SQL last, its continuation lines blank up to the SQL column. */
export function parseTable(out: string): Obj[] {
  const lines = out.split("\n")
  const at = lines.findIndex((l) => /^TYPE\s+NAME\s+TBL NAME\s+SQL\s*$/.test(l))
  if (at < 0) throw new Error("unexpected output from turso db shell: no header")
  const head = lines[at]!
  const [n, t, s] = [head.indexOf("NAME"), head.indexOf("TBL NAME"), head.lastIndexOf("SQL")]
  const objs: Obj[] = []
  for (const l of lines.slice(at + 1)) {
    if (l.slice(0, n).trim()) objs.push({ type: l.slice(0, n).trim(), name: l.slice(n, t).trim(), tbl: l.slice(t, s).trim(), sql: l.slice(s).trimEnd() })
    else if (objs.length) objs.at(-1)!.sql += `\n${l.slice(s).trimEnd()}`
  }
  return objs.map((o) => ({ ...o, sql: o.sql.trimEnd() }))
}

/** What a schema is made of: no engine-owned objects, no FTS shadow tables (the virtual table makes its own). */
export function keepObjects(objs: Obj[]): Obj[] {
  const fts = objs.filter((o) => /^CREATE VIRTUAL TABLE/i.test(o.sql)).map((o) => `${o.name}_`)
  const shadow = (name: string) => fts.some((p) => name.startsWith(p) && /_(data|idx|content|docsize|config)$/.test(name))
  return objs
    .filter((o) => /^CREATE /i.test(o.sql) && !/^(sqlite_|libsql_)/.test(o.name) && !shadow(o.name))
    .sort((a, b) => RANK.indexOf(a.type) - RANK.indexOf(b.type) || a.name.localeCompare(b.name))
}

const norm = (sql: string | undefined) => sql?.replace(/\s+/g, " ").trim()

/** From `live` to `prod`: drop what differs, create what's absent, including what went with a dropped table. */
export function syncPlan(prod: Obj[], live: Obj[]): { drops: string[]; creates: Obj[] } {
  const want = new Map(prod.map((o) => [o.name, o.sql]))
  const stale = live.filter((o) => norm(want.get(o.name)) !== norm(o.sql))
  const gone = new Set(stale.filter((o) => o.type === "table").map((o) => o.name))
  const kept = new Set(live.filter((o) => !stale.includes(o) && !gone.has(o.tbl)).map((o) => o.name))
  const drops = [...stale].sort((a, b) => RANK.indexOf(b.type) - RANK.indexOf(a.type)).map((o) => `DROP ${o.type.toUpperCase()} IF EXISTS "${o.name}"`)
  return { drops, creates: prod.filter((o) => !kept.has(o.name)) }
}

/** The committed subset: the tables tests touch, their indexes and guards, nothing that needs notes_fts or SUBSET_DROP_COLS. */
export function subsetSql(prod: Obj[]): string {
  const objs = prod.filter((o) => SUBSET_TABLES.includes(o.tbl) && !o.name.startsWith("notes_fts") && !/\bnotes_fts\b/.test(o.sql))
  // ponytail: a column def without commas or parens (TEXT DEFAULT NULL); one with a CHECK(...) would need a real parser.
  const drop = (sql: string) => SUBSET_DROP_COLS.reduce((s, c) => s.replace(new RegExp(`,\\s*${c}\\b[^,)]*`), ""), sql)
  return `-- Generated by scripts/turso-test-schema.ts. Do not edit.\n\n${objs.map((o) => `${drop(o.sql)};\n`).join("\n")}`
}

/** The script's only path to tls-test, reads and writes. Every statement goes through the allowlist, whatever the caller passed. */
export function testDbExec(url: string | undefined, token: string): (sql: string) => ReturnType<ExecFn> {
  return async (sql) => {
    process.env.TURSO_DATABASE_URL = testDbUrl(url)
    process.env.TURSO_AUTH_TOKEN = token
    return tursoExec(sql, [])
  }
}

function hranaCell(cell: unknown): string {
  if (!cell || typeof cell !== "object") return ""
  const rec = cell as { type?: unknown; value?: unknown }
  if (rec.type === "null") return ""
  return rec.value === undefined || rec.value === null ? "" : String(rec.value)
}

async function readProd(prodToken: string): Promise<Obj[]> {
  if (!prodToken) throw new Error("TURSO_AUTH_TOKEN is required to read production schema")
  const res = await fetch(PROD_URL, {
    method: "POST",
    headers: { authorization: `Bearer ${prodToken}`, "content-type": "application/json" },
    body: JSON.stringify({ requests: [{ type: "execute", stmt: { sql: PROD_READ } }, { type: "close" }] }),
    signal: AbortSignal.timeout(15_000),
  })
  if (!res.ok) throw new Error(`production schema read failed (http ${res.status})`)
  const body: unknown = await res.json()
  const first = (body && typeof body === "object" ? (body as { results?: unknown[] }).results?.[0] : null) as {
    type?: unknown
    error?: { message?: unknown }
    response?: { result?: { rows?: unknown[] } }
  } | null
  if (!first || first.type !== "ok") {
    throw new Error(`production schema read error: ${String(first?.error?.message ?? "unknown")}`)
  }
  const rows = Array.isArray(first.response?.result?.rows) ? first.response.result.rows : []
  return keepObjects(rows.map((row) => {
    const cells = Array.isArray(row) ? row : []
    return {
      type: hranaCell(cells[0]),
      name: hranaCell(cells[1]),
      tbl: hranaCell(cells[2]),
      sql: hranaCell(cells[3]) || "NULL",
    }
  }))
}

export async function readTest(exec: ReturnType<typeof testDbExec>): Promise<Obj[]> {
  const { rows } = await exec("SELECT type, name, tbl_name AS tbl, sql FROM sqlite_master")
  return keepObjects(rows.map((r) => ({ type: String(r.type), name: String(r.name), tbl: String(r.tbl), sql: String(r.sql ?? "") })))
}

async function main(check: boolean): Promise<number> {
  const prodToken = (process.env.TURSO_AUTH_TOKEN ?? "").trim()
  const url = process.env.TURSO_TEST_URL || `https://${TEST_HOST}`
  const token = (process.env.TURSO_TEST_AUTH_TOKEN ?? "").trim()
  if (!token) throw new Error("TURSO_TEST_AUTH_TOKEN is required to reach tls-sqld-test")
  const prod = await readProd(prodToken)
  const exec = testDbExec(url, token)
  await exec("SELECT 1")
  const plan = syncPlan(prod, await readTest(exec))
  const subset = subsetSql(prod)
  const subsetOk = norm(subset) === norm(await Bun.file(SUBSET_FILE).text().catch(() => ""))
  if (check) {
    for (const d of plan.drops) console.log(`tls-test differs: ${d}`)
    for (const c of plan.creates) console.log(`tls-test lacks: ${c.type} ${c.name}`)
    if (!subsetOk) console.log("server/lib/turso-test-schema.sql differs from production")
    return plan.drops.length || plan.creates.length || !subsetOk ? 1 : 0
  }
  for (const s of plan.drops) await exec(s)
  for (const c of plan.creates) await exec(c.sql)
  const after = syncPlan(prod, await readTest(exec))
  if (after.drops.length || after.creates.length) throw new Error(`tls-test still differs after sync: ${after.drops.length + after.creates.length} objects`)
  await Bun.write(SUBSET_FILE, subset)
  const count = (type: string) => prod.filter((o) => o.type === type).length
  console.log(`tls-test in sync: ${count("table")} tables, ${count("index")} indexes, ${count("trigger")} triggers (${plan.drops.length} dropped, ${plan.creates.length} created)`)
  return 0
}

if (import.meta.main) process.exit(await main(process.argv.includes("--check")))
