#!/usr/bin/env bun
// Keeps tls-test on production's schema. Run by hand after a tls-dashboard-v2 migration, from a host with a turso
// CLI login: `bun scripts/turso-test-schema.ts` syncs, `--check` reports and writes nothing. Production is read with
// one fixed SELECT through `turso db shell` (the CLI has no JSON output, hence parseTable) and nothing else; rows are
// never selected. Writes go through testDbWriter only. The full DDL lives in tls-test: this repo is public, so only
// the tables tests touch are committed, in server/lib/turso-test-schema.sql.

import { join } from "node:path"
import { type Row, tursoExec, tursoQuery } from "../server/lib/turso"
import { testDbUrl } from "../server/lib/turso-test-guard.test-util"

export const PROD_READ = "SELECT type,name,tbl_name,sql FROM sqlite_master"
const PROD_DB = "tls-dashboard"
const TEST_DB = "tls-test"
const SUBSET_FILE = join(import.meta.dir, "../server/lib/turso-test-schema.sql")
const SUBSET_TABLES = ["agent_activity", "notes", "task_stamps", "tasks"]
const RANK = ["table", "view", "index", "trigger"]

export interface Obj { type: string; name: string; tbl: string; sql: string }

/** `turso db shell` output: fixed-width columns, SQL last, its continuation lines blank up to the SQL column. */
export function parseTable(out: string): Obj[] {
  const lines = out.split("\n")
  const at = lines.findIndex((l) => /^TYPE\s+NAME\s+TBL NAME\s+SQL\s*$/.test(l))
  if (at < 0) throw new Error("unexpected output from turso db shell: no header")
  const head = lines[at]!
  const [n, t, s] = [head.indexOf("NAME"), head.indexOf("TBL NAME"), head.lastIndexOf("SQL")]
  const objs: Obj[] = []
  for (const l of lines.slice(at + 1)) {
    if (l.slice(0, n).trim()) objs.push({ type: l.slice(0, n).trim(), name: l.slice(n, t).trim(), tbl: l.slice(t, s).trim(), sql: l.slice(s).trimEnd() })
    else if (objs.length) objs.at(-1)!.sql += `\n${l.slice(s).trimEnd()}`
  }
  return objs.map((o) => ({ ...o, sql: o.sql.trimEnd() }))
}

/** What a schema is made of: no engine-owned objects, no FTS shadow tables (the virtual table makes its own). */
export function keepObjects(objs: Obj[]): Obj[] {
  const fts = objs.filter((o) => /^CREATE VIRTUAL TABLE/i.test(o.sql)).map((o) => `${o.name}_`)
  const shadow = (name: string) => fts.some((p) => name.startsWith(p) && /_(data|idx|content|docsize|config)$/.test(name))
  return objs
    .filter((o) => /^CREATE /i.test(o.sql) && !/^(sqlite_|libsql_)/.test(o.name) && !shadow(o.name))
    .sort((a, b) => RANK.indexOf(a.type) - RANK.indexOf(b.type) || a.name.localeCompare(b.name))
}

const norm = (sql: string | undefined) => sql?.replace(/\s+/g, " ").trim()

/** From `live` to `prod`: drop what differs, create what's absent, including what went with a dropped table. */
export function syncPlan(prod: Obj[], live: Obj[]): { drops: string[]; creates: Obj[] } {
  const want = new Map(prod.map((o) => [o.name, o.sql]))
  const stale = live.filter((o) => norm(want.get(o.name)) !== norm(o.sql))
  const gone = new Set(stale.filter((o) => o.type === "table").map((o) => o.name))
  const kept = new Set(live.filter((o) => !stale.includes(o) && !gone.has(o.tbl)).map((o) => o.name))
  const drops = [...stale].sort((a, b) => RANK.indexOf(b.type) - RANK.indexOf(a.type)).map((o) => `DROP ${o.type.toUpperCase()} IF EXISTS "${o.name}"`)
  return { drops, creates: prod.filter((o) => !kept.has(o.name)) }
}

/** The committed subset: the tables tests touch, their indexes and guards, nothing that needs notes_fts. */
export function subsetSql(prod: Obj[]): string {
  const objs = prod.filter((o) => SUBSET_TABLES.includes(o.tbl) && !o.name.startsWith("notes_fts") && !/\bnotes_fts\b/.test(o.sql))
  return `-- Generated by scripts/turso-test-schema.ts. Do not edit.\n\n${objs.map((o) => `${o.sql};\n`).join("\n")}`
}

/** The script's only write path. Every statement goes through the allowlist, whatever the caller passed. */
export function testDbWriter(url: string | undefined, token: string): (sql: string) => Promise<unknown> {
  return async (sql) => {
    process.env.TURSO_DATABASE_URL = testDbUrl(url)
    process.env.TURSO_AUTH_TOKEN = token
    return tursoExec(sql, [])
  }
}

// Output is kept out of the error: `db tokens create` prints a token.
async function cli(...args: string[]): Promise<string> {
  const r = await Bun.$`turso ${args}`.quiet().nothrow()
  if (r.exitCode !== 0) throw new Error(`turso ${args.slice(0, 2).join(" ")} failed (exit ${r.exitCode})`)
  return r.stdout.toString().trim()
}

const readProd = async () => keepObjects(parseTable(await cli("db", "shell", PROD_DB, PROD_READ)))

async function readTest(): Promise<Obj[]> {
  const rows: Row[] = await tursoQuery("SELECT type, name, tbl_name AS tbl, sql FROM sqlite_master", [])
  return keepObjects(rows.map((r) => ({ type: String(r.type), name: String(r.name), tbl: String(r.tbl), sql: String(r.sql ?? "") })))
}

async function main(check: boolean): Promise<number> {
  const url = await cli("db", "show", TEST_DB, "--url")
  const token = await cli("db", "tokens", "create", TEST_DB, "-e", "1d")
  const write = testDbWriter(url, token)
  await write("SELECT 1")
  const prod = await readProd()
  const plan = syncPlan(prod, await readTest())
  const subset = subsetSql(prod)
  const subsetOk = norm(subset) === norm(await Bun.file(SUBSET_FILE).text().catch(() => ""))
  if (check) {
    for (const d of plan.drops) console.log(`tls-test differs: ${d}`)
    for (const c of plan.creates) console.log(`tls-test lacks: ${c.type} ${c.name}`)
    if (!subsetOk) console.log("server/lib/turso-test-schema.sql differs from production")
    return plan.drops.length || plan.creates.length || !subsetOk ? 1 : 0
  }
  for (const s of plan.drops) await write(s)
  for (const c of plan.creates) await write(c.sql)
  const after = syncPlan(prod, await readTest())
  if (after.drops.length || after.creates.length) throw new Error(`tls-test still differs after sync: ${after.drops.length + after.creates.length} objects`)
  await Bun.write(SUBSET_FILE, subset)
  const count = (type: string) => prod.filter((o) => o.type === type).length
  console.log(`tls-test in sync: ${count("table")} tables, ${count("index")} indexes, ${count("trigger")} triggers (${plan.drops.length} dropped, ${plan.creates.length} created)`)
  return 0
}

if (import.meta.main) process.exit(await main(process.argv.includes("--check")))
